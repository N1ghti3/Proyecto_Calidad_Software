"""ADR-009 — la migración inicial crea el esquema completo y es reversible.

Cada prueba usa una base propia, porque subir y bajar el esquema no puede
compartirse con otras pruebas.
"""

from __future__ import annotations

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from apoyo import configuracion_alembic, conectar, migrar, revertir

TABLAS = {
    "admin_user", "audit_log", "category", "inventory", "notification",
    "order_header", "order_item", "product", "product_image",
    "product_variant", "size_catalog",
}


def _tablas(conn) -> set[str]:
    filas = conn.execute(
        "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
    ).fetchall()
    return {f[0] for f in filas}


def _contar_restricciones(conn, tipo: str) -> int:
    return conn.execute(
        "SELECT count(*) FROM pg_constraint c "
        "JOIN pg_namespace n ON n.oid = c.connamespace "
        "WHERE n.nspname = 'public' AND c.contype = %s",
        (tipo,),
    ).fetchone()[0]


def test_crea_las_once_tablas_desde_una_base_vacia(nueva_base):
    with nueva_base() as base, conectar(base.url_owner) as conn:
        assert _tablas(conn) == TABLAS | {"alembic_version"}


def test_crea_las_restricciones_esperadas(nueva_base):
    # Cifras del README del backend, verificadas a mano el 27/09.
    with nueva_base() as base, conectar(base.url_owner) as conn:
        assert _contar_restricciones(conn, "c") == 40, "restricciones CHECK"
        assert _contar_restricciones(conn, "f") == 9, "claves foráneas"


def test_siembra_el_catalogo_de_tallas(nueva_base):
    # ADR-008: el catálogo de tallas es parte del esquema, no de los datos.
    with nueva_base() as base, conectar(base.url_owner) as conn:
        filas = conn.execute("SELECT code FROM size_catalog ORDER BY position").fetchall()
        assert [f[0] for f in filas] == ["XS", "S", "M", "L", "XL", "XXL", "ÚNICA"]


def test_los_modelos_coinciden_con_el_esquema(nueva_base):
    # Equivale a `alembic check`: si alguien cambia un modelo sin migración,
    # esta prueba falla.
    with nueva_base() as base:
        try:
            command.check(configuracion_alembic(base.url_owner))
        except AutogenerateDiffsDetected as diferencias:
            pytest.fail(f"Modelos y esquema divergen:\n{diferencias}")


def test_downgrade_deja_la_base_vacia_y_se_puede_volver_a_subir(nueva_base):
    with nueva_base() as base:
        revertir(base.url_owner, "base")

        with conectar(base.url_owner) as conn:
            assert _tablas(conn) == {"alembic_version"}
            assert conn.execute(
                "SELECT count(*) FROM pg_proc WHERE proname = 'f_unaccent'"
            ).fetchone()[0] == 0
            assert conn.execute(
                "SELECT count(*) FROM pg_extension WHERE extname IN ('unaccent', 'pg_trgm')"
            ).fetchone()[0] == 0

        migrar(base.url_owner)

        with conectar(base.url_owner) as conn:
            assert _tablas(conn) == TABLAS | {"alembic_version"}


def test_sin_contrasena_del_rol_de_aplicacion_no_toca_la_base(nueva_base, monkeypatch):
    # La migración debe detenerse antes de crear nada: un esquema a medias es
    # peor que ninguno.
    monkeypatch.delenv("APP_DB_PASSWORD")

    def _sin_configuracion():
        raise RuntimeError("sin .env en esta prueba")

    import app.core.config
    monkeypatch.setattr(app.core.config, "obtener_settings", _sin_configuracion)

    with nueva_base(migrada=False) as base:
        with pytest.raises(RuntimeError, match="APP_DB_PASSWORD"):
            migrar(base.url_owner)

        with conectar(base.url_owner) as conn:
            assert _tablas(conn) <= {"alembic_version"}
            assert "product" not in _tablas(conn)
